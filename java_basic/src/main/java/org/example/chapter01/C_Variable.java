package org.example.chapter01;

public class C_Variable {
    public static void main(String[] args) {
        String name; // 문자 열 을 저장하는 공간
        int price; // 숫자를 저장하는 공간
        int num;
        char chr; // 문자 하나를 저장하는 공산
        boolean bool; // 논리  -> 결과가 True or False
        num = 10; // 초기화
        System.out.println(num); //10
        chr = '가';
        bool = true;
        // 초기화 -> 처음 데이터를 넣는 과정
        // 할당 -> 데이터를 바꾸는 과정
        num = 20; // 할당
        System.out.println(num); // 20

    }
}
